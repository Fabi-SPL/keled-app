// Builds the gallery: validates every design in src/ with the hub's own rules, then writes
//   hub/designs/designs.json            what the hub serves at /v1/designs
//   ios/Shared/Bundled/designs.json     the copy the app ships with (works before the hub answers)
//   ios/Shared/Bundled/preview-cards.json  invented cards for the gallery preview and CI shots
//   ios/KeledWidgets/Gallery.swift      one widget per group, generated
// Run: node hub/designs/build.mjs   (npm test checks the outputs are current)

import { createHash } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { normalizeDesign, normalizeCard } from '../store.mjs'
import lock from './src/lock.mjs'
import home from './src/home.mjs'
import more from './src/more.mjs'
import { PREVIEW_CARDS } from './preview-cards.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..', '..')

// One gallery entry per group, in this order; each design is a style inside it.
export const GROUPS = [
  ['overview', 'Wants you', 'Everything that wants you, in one widget.'],
  ['mail', 'Mail', 'Keled Mail: what needs you, per account.'],
  ['office', 'Office', 'The Kels, by face, and who is working.'],
  ['board', 'Board', 'Olympus: Themis, the count, what waits on you.'],
  ['asks', 'Asks', 'Questions and decisions the office holds for you.'],
  ['hq', 'HQ', 'HQ sessions waiting on you.'],
  ['today', 'Today', 'Your habits. Tap a circle to tick it.'],
  ['neural', 'Neural network', 'How fast the neural network grows.'],
  ['calendar', 'Calendar', 'What comes next, with a live countdown.'],
  ['taxes', 'UStVA', 'The next tax deadline.'],
  ['network', 'Network', 'Argus and the tailnet.'],
  ['cura', 'Cura', 'What Cura last wrote.'],
  ['tv', 'TV alerts', 'Lucid TV alerts.'],
]

const SWIFT_FAMILY = {
  small: '.systemSmall', medium: '.systemMedium', large: '.systemLarge', xl: '.systemExtraLarge',
  circular: '.accessoryCircular', rectangular: '.accessoryRectangular', inline: '.accessoryInline',
}
const FAMILY_ORDER = ['small', 'medium', 'large', 'xl', 'circular', 'rectangular', 'inline']

export function build() {
  const errors = []
  const designs = []
  const ids = new Set()
  const groups = new Set(GROUPS.map(([g]) => g))
  for (const raw of [...lock, ...home, ...more].sort((a, b) => a.n - b.n)) {
    const { design, errors: errs } = normalizeDesign(raw)
    for (const e of errs) errors.push(`${raw.id}: ${e}`)
    if (ids.has(raw.id)) errors.push(`${raw.id}: duplicate id`)
    if (!groups.has(raw.group)) errors.push(`${raw.id}: unknown group ${raw.group}`)
    ids.add(raw.id)
    if (design) designs.push(design)
  }
  const cards = []
  // Fixed time so the build is reproducible; ageSec is what the hub adds when it serves a card.
  for (const raw of PREVIEW_CARDS) {
    const { card, errors: errs } = normalizeCard({ ...raw, updatedAt: '2026-10-16T19:41:00.000Z' })
    for (const e of errs ?? []) errors.push(`preview card ${raw.id}: ${e}`)
    if (card) cards.push({ ...card, source: undefined, ageSec: raw.ageSec })
  }
  const known = new Set(cards.map((c) => c.id))
  for (const d of designs) for (const c of d.cards) if (c !== '*' && !known.has(c)) errors.push(`${d.id}: no preview card ${c}`)
  const body = JSON.stringify(designs)
  const version = createHash('sha256').update(body).digest('hex').slice(0, 12)
  return { errors, designs, cards, version }
}

const pascal = (g) => g.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase())
const lit = (s) => JSON.stringify(s)

export function gallerySwift(designs) {
  const out = [
    '// Generated by hub/designs/build.mjs. Do not edit; change the designs and run the build.',
    '// One gallery entry per group; every design in the group is a style in its edit menu.',
    'import WidgetKit',
    'import SwiftUI',
    'import AppIntents',
    '',
  ]
  const widgets = []
  for (const [g, name, description] of GROUPS) {
    const fams = FAMILY_ORDER.filter((f) => designs.some((d) => d.group === g && d.family === f))
    if (!fams.length) continue
    const P = pascal(g)
    widgets.push(`${P}GalleryWidget`)
    out.push(
      `struct ${P}StyleOptions: DynamicOptionsProvider {`,
      `    func results() async throws -> [String] { DesignCatalog.labels(group: ${lit(g)}) }`,
      `}`,
      '',
      `struct ${P}StyleIntent: GalleryStyleIntent {`,
      `    static let group = ${lit(g)}`,
      `    static var title: LocalizedStringResource = ${lit(name)}`,
      `    static var description = IntentDescription(${lit('Pick a style. Each style fits one widget size.')})`,
      '',
      `    @Parameter(title: "Style", optionsProvider: ${P}StyleOptions())`,
      '    var style: String?',
      '',
      '    init() {}',
      `}`,
      '',
      `struct ${P}GalleryWidget: Widget {`,
      '    var body: some WidgetConfiguration {',
      `        Gallery.configuration(kind: ${lit(`keled.design.${g}`)}, intent: ${P}StyleIntent.self, name: ${lit(name)},`,
      `                              description: ${lit(description)}, families: [${fams.map((f) => SWIFT_FAMILY[f]).join(', ')}])`,
      '    }',
      '}',
      '',
    )
  }
  // A WidgetBundle body takes at most ten widgets, so the groups ride in bundles of seven.
  const chunks = []
  for (let i = 0; i < widgets.length; i += 7) chunks.push(widgets.slice(i, i + 7))
  chunks.forEach((chunk, i) => {
    out.push(`struct KeledGallery${i + 1}: WidgetBundle {`, '    var body: some Widget {', ...chunk.map((w) => `        ${w}()`), '    }', '}', '')
  })
  out.push('struct KeledGallery: WidgetBundle {', '    var body: some Widget {', ...chunks.map((_, i) => `        KeledGallery${i + 1}().body`), '    }', '}', '')
  return { swift: out.join('\n'), bundles: chunks.length }
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const { errors, designs, cards, version } = build()
  if (errors.length) {
    console.error(errors.join('\n'))
    process.exit(1)
  }
  const served = JSON.stringify({ version, designs }, null, 1)
  const bundled = join(ROOT, 'ios', 'Shared', 'Bundled')
  mkdirSync(bundled, { recursive: true })
  writeFileSync(join(HERE, 'designs.json'), served + '\n')
  writeFileSync(join(bundled, 'designs.json'), served + '\n')
  writeFileSync(join(bundled, 'preview-cards.json'), JSON.stringify(cards, null, 1) + '\n')
  const { swift } = gallerySwift(designs)
  writeFileSync(join(ROOT, 'ios', 'KeledWidgets', 'Gallery.swift'), swift)
  const byGroup = {}
  for (const d of designs) byGroup[d.group] = (byGroup[d.group] ?? 0) + 1
  console.log(`${designs.length} designs, version ${version}`)
  console.log(Object.entries(byGroup).map(([g, n]) => `${g} ${n}`).join(' · '))
}
